function between(s, start, end) {
  const a = s.indexOf(start);
  if (a === -1) return null;
  const b = s.indexOf(end, a);
  if (b === -1) throw new Error(`opening marker without its closing pair: ${start}`);
  return [a, b + end.length];
}

function build(page) {
  const path = join(ROOT, page.file);
  if (!existsSync(path)) throw new Error(`missing page ${page.file}`);
  let s = readFileSync(path, 'utf8');

  const routes = { ...(page.mobile ? MOBILE : DESKTOP), ...(page.self ? SELF_ANCHORS : {}) };
  const markup = html(routes, page.current);

  /* CSS goes last in <head> so it outranks the page's own stylesheet without
     needing !important against four different sets of base `a` rules. */
  const cssSpan = between(s, CSS_START, CSS_END);
  if (cssSpan) {
    s = s.slice(0, cssSpan[0]) + CSS + s.slice(cssSpan[1]);
  } else {
    if (!s.includes('</head>')) throw new Error(`${page.file}: no </head>`);
    s = s.replace('</head>', `${CSS}\n</head>`);
  }

  const htmlSpan = between(s, HTML_START, HTML_END);
  if (htmlSpan) {
    s = s.slice(0, htmlSpan[0]) + markup + s.slice(htmlSpan[1]);
  } else {
    /* First run: take over whatever footer the page already had, in place, so
       the document structure (e.g. /partners' x-dc wrapper) is preserved. */
    const old = s.match(/[ \t]*<footer[\s\S]*?<\/footer>/);
    if (old) {
      s = s.slice(0, old.index) + markup + s.slice(old.index + old[0].length);
    } else if (s.includes('</body>')) {
      s = s.replace('</body>', `${markup}\n</body>`);
    } else {
      throw new Error(`${page.file}: no <footer> and no </body>`);
    }
  }
  return { path, next: s };
}

let stale = 0;
let written = 0;
for (const page of PAGES) {
  const { path, next } = build(page);
  const prev = readFileSync(path, 'utf8');
  if (prev === next) continue;
  if (CHECK) {
    console.error(`STALE   ${page.file}: regenerate with: node scripts/build-footer.mjs`);
    stale++;
    continue;
  }
  writeFileSync(path, next);
  console.log(`written ${page.file}`);
  written++;
}

if (CHECK && stale) {
  console.error(`\n${stale} page(s) have a stale footer.`);
  process.exit(1);
}
console.log(CHECK
  ? `ok      ${PAGES.length} page(s) carry the current footer`
  : `\n${written} page(s) updated, ${PAGES.length} total.`);
