/* Generate the shared site footer into every page.
 *
 * WHY
 * The footer was hand-copied into each page, so it drifted: /partners still
 * linked "Company", "LinkedIn" and "Legal" at href="#", the blog pages carried
 * a one-line copyright with no navigation at all, and the checkout-ish pages
 * (waitlist, thank-you, logins, dashboards) had no footer whatsoever. Editing
 * the nav meant finding and re-typing it in 35 files, which is exactly how the
 * dead links survived. The footer is now defined once, here, and written into
 * every page between markers.
 *
 *   node scripts/build-footer.mjs          # write the footer into every page
 *   node scripts/build-footer.mjs --check  # CI: fail if any page is stale
 *
 * ORDER
 * Run this BEFORE scripts/build-mobile-pages.mjs: bill-checkup-mobile and
 * become-a-partner-mobile are generated from their desktop sources, so they
 * inherit the footer (and its mobile link rewrites) from there rather than
 * being listed below.
 *
 * The markup is deliberately self-contained, its own colours, spacing and
 * font stack, because it drops into four unrelated design systems (the site
 * pages, the cream legal pages, the serif blog and the provider deck). It must
 * not depend on a page defining --navy-deep, --disp or any other token.
 */

