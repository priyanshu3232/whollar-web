#!/usr/bin/env node
/* Generate MobileVersion/*.html from their desktop sources.
 *
 * WHY
 * The mobile pages were hand-maintained copies of the desktop ones, and they
 * had already drifted in ways nobody noticed: the mobile estimator CTA pointed
 * at the waitlist instead of the checkup, mobile had no login link three weeks
 * after logins shipped, and every em dash in mobile copy had become a comma so
 * the two decks could no longer be diffed. Twelve files, six pages, no build
 * step, no test.
 *
 * A mobile page is now defined as exactly three things:
 *   1. its desktop source
 *   2. a link-rewrite map (desktop route -> MobileVersion route)
 *   3. a CSS overlay in MobileVersion/overlays/<page>.css
 * Nothing else may differ. Copy edits to the desktop page reach mobile by
 * running this script; they cannot silently miss it.
 *
 *   node scripts/build-mobile-pages.mjs          # write the mobile files
 *   node scripts/build-mobile-pages.mjs --check  # CI: fail if they are stale
 *
 * NOT handled here (different mechanisms, still hand-maintained):
 *   - index.html / partners.html and their mobile builds (consumer-mobile,
 *     provider-mobile) are separate hand-edited pages; they were converted
 *     from self-unpacking bundles to plain HTML by scripts/debundle.mjs.
 *   - waitlist <-> join-the-first-cohort-mobile: the mobile build inlines
 *     Lottie JSON and fonts that the desktop page loads as separate files.
 *   - blog articles: see scripts/build-mobile-blog.mjs.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

/* Desktop route -> mobile route. Longest keys first so "/blog/" is rewritten
   before "/". Routes with no mobile counterpart (/terms, /privacy,
   /disclosures, /favicon.svg) are deliberately absent and pass through. */
const ROUTE_MAP = [
  ['/become-a-partner', '/MobileVersion/become-a-partner-mobile'],
  ['/bill-checkup', '/MobileVersion/bill-checkup-mobile'],
  ['/waitlist/', '/MobileVersion/join-the-first-cohort-mobile'],
  ['/waitlist', '/MobileVersion/join-the-first-cohort-mobile'],
  ['/partners', '/MobileVersion/provider-mobile'],
  ['/blog/', '/MobileVersion/resources-mobile'],
  ['/blog', '/MobileVersion/resources-mobile'],
  ['/', '/MobileVersion/consumer-mobile']
];

const PAGES = [
  {
    source: 'bill-checkup.html',
    output: 'MobileVersion/bill-checkup-mobile.html',
    overlay: 'MobileVersion/overlays/bill-checkup.css',
    canonical: 'https://www.whollar.ca/bill-checkup'
  },
  {
    source: 'become-a-partner.html',
    output: 'MobileVersion/become-a-partner-mobile.html',
    overlay: 'MobileVersion/overlays/become-a-partner.css',
    canonical: 'https://www.whollar.ca/become-a-partner'
  }
];

/* Rewrite only href/action targets, never arbitrary text — a bare "/" inside
   copy or a regex must not be touched. */
function rewriteLinks(html) {
  return html.replace(/(\b(?:href|action)=")([^"]*)(")/g, (full, pre, url, post) => {
    if (/^(https?:|mailto:|tel:|#|data:)/i.test(url)) return full;
    const hit = ROUTE_MAP.find(([from]) => url === from);
    return hit ? pre + hit[1] + post : full;
  });
}

/* The mobile page is a duplicate of a desktop URL. Without a canonical both
   are indexable as separate pages — 8 duplicate URLs across the four pairs. */
function forceCanonical(html, url) {
  const tag = `<link rel="canonical" href="${url}">`;
  return /<link rel="canonical"[^>]*>/.test(html)
    ? html.replace(/<link rel="canonical"[^>]*>/, tag)
    : html.replace('</title>', '</title>\n' + tag);
}

function build(page) {
  const src = readFileSync(join(ROOT, page.source), 'utf8');
  if (!existsSync(join(ROOT, page.overlay))) {
    throw new Error(`missing overlay ${page.overlay} for ${page.source}`);
  }
  const overlay = readFileSync(join(ROOT, page.overlay), 'utf8').trim();

  let out = rewriteLinks(src);
  out = forceCanonical(out, page.canonical);

  /* Strip any previously generated overlay so rebuilds are idempotent. */
  out = out.replace(/\n?<style id="whl-mobile">[\s\S]*?<\/style>\n?/, '\n');

  const banner = `<!-- GENERATED by scripts/build-mobile-pages.mjs from ${page.source}.
     Do NOT edit this file. Edit ${page.source} for content, or
     ${page.overlay} for mobile-only styling, then re-run the script. -->\n`;

  out = out.replace('</body>', `<style id="whl-mobile">\n${overlay}\n</style>\n</body>`);
  out = out.replace('<head>', '<head>\n' + banner.trimEnd());

  return out;
}

let stale = 0;
for (const page of PAGES) {
  const next = build(page);
  const path = join(ROOT, page.output);
  const prev = existsSync(path) ? readFileSync(path, 'utf8') : null;

  if (prev === next) {
    console.log(`ok      ${page.output}`);
    continue;
  }
  if (CHECK) {
    console.error(`STALE   ${page.output} — regenerate with: node scripts/build-mobile-pages.mjs`);
    stale++;
    continue;
  }
  writeFileSync(path, next);
  console.log(`written ${page.output}  (${next.length.toLocaleString()} bytes)`);
}

if (CHECK && stale) {
  console.error(`\n${stale} mobile page(s) out of sync with their desktop source.`);
  process.exit(1);
}
