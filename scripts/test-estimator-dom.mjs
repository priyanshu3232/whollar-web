#!/usr/bin/env node
/* DOM acceptance tests for the homepage quick estimate ("What could you
 * save?"), the widget wired to WHOLLAR.quickEstimate.
 *
 * Run: node --test scripts/test-estimator-dom.mjs
 *
 * Drives the real / page in headless Chrome via playwright-core (a
 * devDependency; no browser download, the system Chrome is used). The repo's
 * own dev server serves the page; every external host is blocked and the
 * /calculator-estimate POST is intercepted so the request BODY can be
 * asserted, which is how the "FSA only, never the full postal code" rule is
 * held. Runs offline and writes nothing.
 *
 * scripts/test-quick-estimate.mjs covers the arithmetic. This file covers
 * only what the pure functions cannot see: that the wiring renders the right
 * path, that the province basis reaches the copy, and that nothing but the
 * FSA leaves the browser.
 */
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { existsSync } from 'node:fs';
import { chromium } from 'playwright-core';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 4321;
const BASE = `http://localhost:${PORT}`;

const CHROME_PATHS = [
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/google-chrome-stable',
  '/usr/bin/chromium-browser',
  '/usr/bin/chromium'
];

let server, browser, consoleErrors = [], posted = [];

/* The two surfaces carrying this widget. MobileVersion/consumer-mobile.html
   is NOT generated by scripts/build-mobile-pages.mjs (see that script's
   header), so it is a hand-maintained copy and the only thing stopping it
   drifting back to the retired province-only estimator is this list. */
const SURFACES = [
  ['desktop', '/', 1280],
  ['mobile', '/MobileVersion/consumer-mobile', 390]
];

async function newPage(path = '/', width = 1280) {
  const ctx = await browser.newContext({ viewport: { width, height: 900 } });
  await ctx.route('**/*', route => {
    const url = route.request().url();
    if (url.startsWith(BASE)) return route.continue();
    if (url.includes('/calculator-estimate')) {
      let body = null;
      try { body = JSON.parse(route.request().postData() || 'null'); } catch (e) { /* asserted as null */ }
      posted.push(body);
      return route.fulfill({ status: 200, contentType: 'application/json', body: '{"ok":true,"id":"test"}' });
    }
    if (url.includes('/api/auth/') || url.includes('catalystserverless')) {
      return route.fulfill({ status: 401, contentType: 'application/json', body: '{"ok":false}' });
    }
    return route.abort(); /* fonts, clarity, everything third-party */
  });
  const page = await ctx.newPage();
  page.on('console', m => {
    if (m.type() !== 'error') return;
    const text = m.text();
    if (/net::|Failed to load resource|ERR_FAILED|status of 401/.test(text)) return;
    consoleErrors.push(text);
  });
  page.on('pageerror', e => consoleErrors.push(String(e)));
  await page.goto(BASE + path, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.WHOLLAR && window.WHOLLAR.quickEstimate);
  return page;
}

/* Fill both inputs and press the button. The handler waits 700ms before it
   paints, so the result is awaited rather than assumed. */
async function estimate(page, { bill, postal }) {
  await page.fill('[data-bill-input]', String(bill));
  await page.dispatchEvent('[data-bill-input]', 'input');
  await page.fill('[data-postal]', postal);
  await page.dispatchEvent('[data-postal]', 'input');
  await page.click('[data-calc-btn]');
  await page.waitForSelector('[data-est-result].is-shown', { timeout: 4000 });
  await page.waitForFunction(() => {
    const b = document.querySelector('[data-save-basis]');
    const p = document.querySelector('[data-save-pre]');
    return (b && b.textContent.trim()) || (p && /Enter/.test(p.textContent));
  }, { timeout: 4000 });
  return page.evaluate(() => ({
    pre: document.querySelector('[data-save-pre]').textContent.trim(),
    num: document.querySelector('[data-save]').textContent.trim(),
    basis: document.querySelector('[data-save-basis]').textContent.trim(),
    note: document.querySelector('[data-save-note]').textContent.trim(),
    unitShown: document.querySelector('[data-save-unit]').style.display !== 'none'
  }));
}

test.before(async () => {
  const bin = CHROME_PATHS.find(p => existsSync(p));
  if (!bin) throw new Error('no Chrome/Chromium found for the DOM tests');
  server = spawn(process.execPath, [join(ROOT, 'scripts/dev-server.mjs')], {
    cwd: ROOT, stdio: 'ignore', env: { ...process.env, PORT: String(PORT) }
  });
  /* Poll rather than sleep: the server is ready when it answers. */
  for (let i = 0; i < 100; i++) {
    try { const r = await fetch(BASE + '/'); if (r.ok) break; } catch (e) { /* not up yet */ }
    await new Promise(r => setTimeout(r, 100));
  }
  browser = await chromium.launch({ executablePath: bin });
});

test.after(async () => {
  if (browser) await browser.close();
  if (server) server.kill();
});

for (const [name, path, width] of SURFACES) {
  test(`a city-basis estimate names the provider, the speed and the city [${name}]`, async () => {
    const page = await newPage(path, width);
    const r = await estimate(page, { bill: 90, postal: 'M5V 3A8' });
    assert.match(r.pre, /^Estimated/, 'the heading must say "Estimated", not "you will save"');
    assert.match(r.num, /^\$\d/);
    assert.match(r.basis, /cheapest advertised plan at \d+ Mbps or better in Toronto/);
    assert.match(r.basis, /\$\d+ a month/, 'the benchmark price is shown');
    assert.match(r.note, /reseller/i, 'the card is labelled reseller-benchmarked');
    assert.equal(r.unitShown, true);
    await page.close();
  });

  test(`a province-basis estimate says "across", never a city [${name}]`, async () => {
    const page = await newPage(path, width);
    const r = await estimate(page, { bill: 90, postal: 'G0A 1A0' });
    assert.match(r.basis, /across Quebec/);
    assert.doesNotMatch(r.basis, / in [A-Z]/, 'a province number must not read as local');
    await page.close();
  });

  test(`a bill at or below the benchmark shows no figure and no negative [${name}]`, async () => {
    const page = await newPage(path, width);
    const bench = await page.evaluate(() => window.WHOLLAR.estimateBenchFor('M5V 3A8').p);
    const r = await estimate(page, { bill: Math.max(20, bench - 5), postal: 'M5V 3A8' });
    assert.match(r.pre, /already at or below the tracked frontier/);
    assert.equal(r.num, '', 'no figure at all on this path');
    assert.equal(r.unitShown, false, '"/ year" must not hang off an empty number');
    assert.doesNotMatch(r.pre + r.basis, /-\$|\$-/, 'no negative figure anywhere');
    assert.match(r.basis, /cheapest advertised plan/, 'the comparison is still explained');
    await page.close();
  });

  test(`only the FSA is sent to the backend, never the full postal code [${name}]`, async () => {
    posted = [];
    const page = await newPage(path, width);
    await estimate(page, { bill: 90, postal: 'M5V 3A8' });
    assert.equal(posted.length, 1, 'exactly one estimate was recorded');
    const body = posted[0];
    assert.ok(body, 'the POST body was not valid JSON');
    assert.equal(body.fsa, 'M5V');
    assert.equal('postal' in body, false, 'the full postal code was sent');
    const flat = JSON.stringify(body);
    assert.doesNotMatch(flat, /3A8/, 'the last three characters leaked into the payload');
    assert.equal(body.monthlyBill, 90);
    assert.ok(body.estimatedAnnualSavings >= 0 && body.estimatedAnnualSavings <= 5000);
    await page.close();
  });

  test(`an out-of-range bill is refused and nothing is recorded [${name}]`, async () => {
    posted = [];
    const page = await newPage(path, width);
    await page.fill('[data-bill-input]', '5');
    await page.dispatchEvent('[data-bill-input]', 'input');
    await page.fill('[data-postal]', 'M5V 3A8');
    await page.dispatchEvent('[data-postal]', 'input');
    await page.click('[data-calc-btn]');
    await page.waitForTimeout(1200);
    assert.equal(await page.isVisible('[data-est-result].is-shown'), false, 'a $5 bill produced a result');
    assert.equal(await page.evaluate(() => document.querySelector('[data-bill-input]').classList.contains('is-err')), true);
    assert.equal(posted.length, 0, 'a rejected estimate was still recorded');
    await page.close();
  });

  test(`an invalid postal code is refused and nothing is recorded [${name}]`, async () => {
    posted = [];
    const page = await newPage(path, width);
    await page.fill('[data-bill-input]', '90');
    await page.dispatchEvent('[data-bill-input]', 'input');
    await page.fill('[data-postal]', 'ZZZ 9Q9');
    await page.dispatchEvent('[data-postal]', 'input');
    await page.click('[data-calc-btn]');
    await page.waitForTimeout(1200);
    assert.equal(await page.isVisible('[data-est-result].is-shown'), false);
    assert.equal(await page.evaluate(() => document.querySelector('[data-postal]').classList.contains('is-err')), true);
    assert.equal(posted.length, 0);
    await page.close();
  });

  /* The button hides itself after the first run, so editing the postal code
     afterwards has to refresh the number in place or the card silently shows
     another city's price. */
  test(`editing the postal code after the first run refreshes the estimate [${name}]`, async () => {
    const page = await newPage(path, width);
    const first = await estimate(page, { bill: 90, postal: 'M5V 3A8' });
    assert.match(first.basis, /in Toronto/);
    await page.fill('[data-postal]', 'V6B 1A1');
    await page.dispatchEvent('[data-postal]', 'input');
    await page.waitForFunction(() =>
      /in Vancouver/.test(document.querySelector('[data-save-basis]').textContent), { timeout: 4000 });
    await page.close();
  });
}

test('the page produced no console errors', () => {
  assert.deepEqual(consoleErrors, []);
});
